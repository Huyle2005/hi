@app.route('/api/gate-event', methods=['POST'])
def handle_gate_event():
    data = request.get_json(silent=True) or {}

    plate = (data.get('plate') or '').strip()
    action = (data.get('action') or '').strip().upper()

    rfid_uid = (
        data.get('rfid_uid')
        or data.get('uid')
        or 'UNKNOWN'
    )
    tx = data.get('tx')

    # Thời gian Việt Nam
    now_time = datetime.now(
        ZoneInfo("Asia/Ho_Chi_Minh")
    ).strftime('%H:%M')

    if action not in ('IN', 'OUT'):
        return jsonify({
            "success": False,
            "message": "action phải là IN hoặc OUT"
        }), 400

    if not plate:
        with get_db() as conn:
            conn.execute("""
                INSERT INTO rfid_logs
                    (rfid_uid, tx, event_type, status)
                VALUES (%s, %s, %s, %s)
            """, (
                rfid_uid, tx, action, 'MISSING_PLATE'
            ))

        return jsonify({
            "success": False,
            "message": "Thiếu biển số xe"
        }), 400

    try:
        # Cập nhật lịch trình và ghi log trong cùng transaction
        with get_db() as conn:
            schedule = conn.execute("""
                SELECT s.id, s.status
                FROM schedules s
                JOIN vehicles v ON s.vehicle_id = v.id
                WHERE v.plate = %s
                ORDER BY s.id DESC
                LIMIT 1
            """, (plate,)).fetchone()

            if not schedule:
                conn.execute("""
                    INSERT INTO rfid_logs
                        (rfid_uid, tx, event_type, status)
                    VALUES (%s, %s, %s, %s)
                """, (
                    rfid_uid, tx, action,
                    'SCHEDULE_NOT_FOUND'
                ))

                result = {
                    "success": False,
                    "message": (
                        "Không tìm thấy lịch trình "
                        "đăng ký cho xe này"
                    )
                }
                status_code = 404

            else:
                if action == 'OUT':
                    conn.execute("""
                        UPDATE schedules
                        SET actual_dep_time = %s,
                            status = 'Đang chạy'
                        WHERE id = %s
                    """, (now_time, schedule['id']))

                else:  # action == 'IN'
                    conn.execute("""
                        UPDATE schedules
                        SET actual_ret_time = %s,
                            status = 'Đã về bãi'
                        WHERE id = %s
                    """, (now_time, schedule['id']))

                # Ghi lịch sử quét vào bảng riêng
                conn.execute("""
                    INSERT INTO rfid_logs
                        (rfid_uid, tx, event_type, status)
                    VALUES (%s, %s, %s, %s)
                """, (
                    rfid_uid, tx, action, 'SUCCESS'
                ))

                result = {
                    "success": True,
                    "plate": plate,
                    "action": action,
                    "time": now_time,
                    "message": (
                        f"Cập nhật thời gian xe {plate} "
                        f"thành công lúc {now_time}"
                    )
                }
                status_code = 200

        return jsonify(result), status_code

    except Exception:
        app.logger.exception(
            "Lỗi cập nhật thời gian vào/ra và lưu RFID log"
        )
        return jsonify({
            "success": False,
            "message": "Không lưu được thời gian vào/ra"
        }), 500

