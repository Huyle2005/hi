def get_db():
    database_url = os.environ.get("DATABASE_URL")

    if not database_url:
        raise RuntimeError("Chưa cấu hình DATABASE_URL trên Render")

    if database_url.startswith("postgres://"):
        database_url = database_url.replace(
            "postgres://", "postgresql://", 1
        )

    return psycopg.connect(database_url, row_factory=dict_row)



def init_db():
    with get_db() as conn:
        cursor = conn.cursor()

        # 1. Bảng Users
        

        # 2. Bảng Tài xế
        cursor.execute('''
            CREATE TABLE IF NOT EXISTS drivers (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                code TEXT UNIQUE NOT NULL,
                name TEXT NOT NULL,
                age INTEGER,
                gender TEXT,
                phone TEXT,
                face_img1 TEXT,
                face_img2 TEXT,
                face_img3 TEXT
            )
        ''')

        # 3. Bảng Phương tiện
        cursor.execute('''
            CREATE TABLE IF NOT EXISTS vehicles (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                plate TEXT UNIQUE NOT NULL,
                vehicle_type TEXT NOT NULL
            )
        ''')

        # 4. Bảng Lịch trình (Giờ thực tế mặc định trống, chờ Raspberry Pi ghi nhận)
        cursor.execute('''
            CREATE TABLE IF NOT EXISTS schedules (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                driver_id BIGINT NOT NULL,
                vehicle_id BIGINT NOT NULL,
                departure_time TEXT NOT NULL,
                return_time TEXT,
                actual_dep_time TEXT DEFAULT '',
                actual_ret_time TEXT DEFAULT '',
                status TEXT DEFAULT 'Chờ xuất bến',
                FOREIGN KEY (driver_id) REFERENCES drivers (id) ON DELETE CASCADE,
                FOREIGN KEY (vehicle_id) REFERENCES vehicles (id) ON DELETE CASCADE
            )
        ''')

        # 5. Bảng Sự cố
        cursor.execute('''
            CREATE TABLE IF NOT EXISTS incidents (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                created_at TEXT NOT NULL,
                plate TEXT NOT NULL,
                driver_name TEXT NOT NULL,
                error_type TEXT NOT NULL,
                status TEXT DEFAULT 'Chờ xử lý'
            )
        ''')

        # Bổ sung metadata lịch sử ra/vào, không làm mất dữ liệu cũ.
        cursor.execute("""
            ALTER TABLE rfid_logs
                ADD COLUMN IF NOT EXISTS event_id TEXT,
                ADD COLUMN IF NOT EXISTS driver_code TEXT,
                ADD COLUMN IF NOT EXISTS driver_name TEXT,
                ADD COLUMN IF NOT EXISTS plate TEXT,
                ADD COLUMN IF NOT EXISTS gate TEXT,
                ADD COLUMN IF NOT EXISTS decision TEXT,
                ADD COLUMN IF NOT EXISTS message TEXT,
                ADD COLUMN IF NOT EXISTS plate_source TEXT,
                ADD COLUMN IF NOT EXISTS face_image_public_id TEXT,
                ADD COLUMN IF NOT EXISTS plate_image_public_id TEXT
        """)
        cursor.execute("""
            CREATE UNIQUE INDEX IF NOT EXISTS rfid_logs_event_id_uidx
            ON rfid_logs (event_id) WHERE event_id IS NOT NULL
        """)
        conn.commit()



